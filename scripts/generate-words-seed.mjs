/**
 * scripts/generate-words-seed.mjs
 *
 * Reads the RAW word arrays from scripts/words/*.ts and generates
 * supabase_words_seed.sql with all words for the `words` table.
 *
 * Usage:  node scripts/generate-words-seed.mjs
 */

import { readFileSync, writeFileSync } from 'fs'

const FILES = [
  { file: 'scripts/words/a1.ts', varName: 'A1_RAW', level: 'A1' },
  { file: 'scripts/words/a2.ts', varName: 'A2_RAW', level: 'A2' },
  { file: 'scripts/words/b1.ts', varName: 'B1_PHRASAL_RAW', level: 'B1' },
  { file: 'scripts/words/b1.ts', varName: 'B1_GENERAL_RAW', level: 'B1' },
  { file: 'scripts/words/b2.ts', varName: 'B2_IDIOM_RAW', level: 'B2' },
  { file: 'scripts/words/b2.ts', varName: 'B2_ACADEMIC_RAW', level: 'B2' },
  { file: 'scripts/words/b2.ts', varName: 'B2_GENERAL_RAW', level: 'B2' },
]

// Regex to match:   ['word', 'tarjima', '/fonetik/', 'example'],
const TUPLE_RE = /\[\s*'((?:[^'\\]|\\.)*)'\s*,\s*'((?:[^'\\]|\\.)*)'\s*,\s*'((?:[^'\\]|\\.)*)'\s*,\s*'((?:[^'\\]|\\.)*)'\s*\],?\s*/g

function escapeSql(s) {
  return s.replace(/'/g, "''")
}

function unescapeJs(s) {
  return s.replace(/\\(['"\\])/g, '$1')
}

/**
 * Extract only the tuples belonging to a specific array variable.
 * Strategy: find `export const VARNAME`, then track bracket depth
 * to know where the array ends.
 */
function extractTuples(content, varName) {
  const startMarker = `export const ${varName}`
  const startIdx = content.indexOf(startMarker)
  if (startIdx === -1) {
    console.warn(`  ⚠ ${varName} not found in file`)
    return []
  }

  const slice = content.slice(startIdx)

  // Find the opening bracket after `= [`
  const assignIdx = slice.indexOf('= [')
  if (assignIdx === -1) return []
  const bracketIdx = assignIdx + 2 // position of the actual `[`

  // From the opening bracket, track depth to find the closing bracket
  let depth = 0
  let endIdx = bracketIdx
  for (let i = bracketIdx; i < slice.length; i++) {
    const ch = slice[i]
    if (ch === '[') depth++
    else if (ch === ']') {
      depth--
      if (depth === 0) {
        endIdx = i + 1
        break
      }
    }
  }

  const arrayContent = slice.slice(bracketIdx, endIdx)

  const tuples = []
  let match
  while ((match = TUPLE_RE.exec(arrayContent)) !== null) {
    tuples.push({
      english:   unescapeJs(match[1].trim()),
      uzbek:     unescapeJs(match[2].trim()),
      phonetic:  unescapeJs(match[3].trim()),
      example:   unescapeJs(match[4].trim()),
    })
  }
  return tuples
}

function main() {
  const seen = new Set()
  const all = []

  for (const { file, varName, level } of FILES) {
    const content = readFileSync(file, 'utf-8')
    const tuples = extractTuples(content, varName)
    console.log(`  ${varName} (${level}): ${tuples.length} ta`)

    for (const t of tuples) {
      const key = `${t.english.toLowerCase()}|${level}`
      if (seen.has(key)) continue
      seen.add(key)
      all.push({ ...t, level })
    }
  }

  console.log(`\nJami (unique): ${all.length} ta`)

  // Count by level
  const byLevel = {}
  for (const w of all) {
    byLevel[w.level] = (byLevel[w.level] ?? 0) + 1
  }
  for (const [lvl, count] of Object.entries(byLevel)) {
    console.log(`  ${lvl}: ${count} ta`)
  }

  // Generate SQL
  const BATCH = 500
  const inserts = []
  for (let i = 0; i < all.length; i += BATCH) {
    const batch = all.slice(i, i + BATCH)
    const rows = batch.map((w) =>
      `  ('${escapeSql(w.english.toLowerCase())}', '${escapeSql(w.uzbek)}', '${w.level}', '${escapeSql(w.example)}', '${escapeSql(w.phonetic)}')`
    )
    inserts.push(
      `insert into public.words (english, uzbek, level, example, phonetic) values\n${rows.join(',\n')}\non conflict (english, level) do nothing;`
    )
  }

  const sql = `-- ═══════════════════════════════════════════════════════════════════════════
-- EnglishPath — Complete Words Seed (${all.length} words)
-- Run this in: Supabase Dashboard → SQL Editor → New query → Run
-- Generated by scripts/generate-words-seed.mjs
--
-- NOTE: This file only seeds the \`words\` table and creates \`user_words\` table.
--       If you haven't run supabase_schema.sql yet, do that first for other tables.
-- ═══════════════════════════════════════════════════════════════════════════

-- ─── Words catalog table (idempotent) ─────────────────────────────────────────
create table if not exists public.words (
  id       bigserial primary key,
  english  text not null,
  uzbek    text not null,
  level    text not null check (level in ('A1','A2','B1','B2')),
  example  text not null default '',
  phonetic text not null default '',
  unique (english, level)
);

alter table public.words enable row level security;

drop policy if exists "Words are readable by all authenticated users" on public.words;
create policy "Words are readable by all authenticated users"
  on public.words for select
  using (auth.role() = 'authenticated');

-- ─── User words table (personal dictionary) ───────────────────────────────────
create table if not exists public.user_words (
  id        bigserial primary key,
  user_id   uuid        not null references auth.users(id) on delete cascade,
  english   text        not null,
  uzbek     text        not null,
  level     text        not null default 'A2' check (level in ('A1','A2','B1','B2')),
  example   text        not null default '',
  phonetic  text        not null default '',
  created_at timestamptz not null default now(),
  unique (user_id, english)
);

alter table public.user_words enable row level security;

drop policy if exists "Users can read own words" on public.user_words;
create policy "Users can read own words"
  on public.user_words for select
  using (auth.uid() = user_id);

drop policy if exists "Users can insert own words" on public.user_words;
create policy "Users can insert own words"
  on public.user_words for insert
  with check (auth.uid() = user_id);

drop policy if exists "Users can delete own words" on public.user_words;
create policy "Users can delete own words"
  on public.user_words for delete
  using (auth.uid() = user_id);

-- ─── Seed all words ───────────────────────────────────────────────────────────

${inserts.join('\n\n')}

-- Verify
do $$
declare
  a1_cnt int; a2_cnt int; b1_cnt int; b2_cnt int;
begin
  select count(*) into a1_cnt from public.words where level = 'A1';
  select count(*) into a2_cnt from public.words where level = 'A2';
  select count(*) into b1_cnt from public.words where level = 'B1';
  select count(*) into b2_cnt from public.words where level = 'B2';
  raise notice '✅ Words seed complete — A1: %, A2: %, B1: %, B2: % (total: %)',
    a1_cnt, a2_cnt, b1_cnt, b2_cnt, a1_cnt + a2_cnt + b1_cnt + b2_cnt;
end $$;
`

  const outPath = 'supabase_words_seed.sql'
  writeFileSync(outPath, sql, 'utf-8')
  console.log(`\n✅ ${outPath} yaratildi (${all.length} so'z)`)
}

main()
